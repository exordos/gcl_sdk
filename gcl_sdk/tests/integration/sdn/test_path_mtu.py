"""A guest whose packet is too big for the path has to be told so.

An overlay costs header room, so the way out is narrower than a guest's own
link almost by construction, and the only mechanism that copes with that is
one ICMP message -- fragmentation-needed, carrying the size that would have
fit. It is invisible when it works and silent when it does not: a connection
completes its handshake, carries small packets, and hangs forever on the
first large one, with nothing in any log to say why.

Two separate things have to hold, and they are tested apart because they
fail apart. The gateway must *generate* the message -- that is the router's
job, and it happens in the per-VNI namespace where the transfer leg is the
narrow hop. And the guest's own allow-list must *admit* it, which is what
`+rel` buys and what nothing else in the pipeline would let through; before
that fix this file could not have been written, because the error died at
the guest's port with the ping looking like an ordinary timeout.

So the narrowing is put beyond the gateway rather than on the guest's link,
which is where a real deployment's narrowing lives too -- an underlay that
lost room to encapsulation somewhere past the hypervisor. Note the sizes
below stay under the gateway leg's own 1450: a packet larger than *that*
never reaches the router at all, it is dropped at the veth boundary with no
ICMP from anyone, which is a black hole of a different kind and not this
one.

OVN keeps `pmtud` cases across its tunnel types, Neutron a scenario pair on
network MTU, and ovn-kubernetes a "works with pmtud" case.
"""

import subprocess

import pytest

from gcl_sdk.agents.universal.drivers.evpn import hostns
from gcl_sdk.tests.integration.sdn import harness

VNI = 16112
CIDR = "10.42.13.0/24"
GW = "10.42.13.1"
GUEST_IP = "10.42.13.5"
# Somewhere off-subnet. Nothing answers a documentation address and nothing
# needs to: the error under test is generated by the gateway on the way out,
# before anything at the far end is involved.
FAR = "192.0.2.7"

# The gateway leg is 1450 (the overlay MTU the driver configures). The hop
# past it is made narrower than that on purpose, and the probe sized to fit
# through the first and not the second.
NARROW_MTU = 1300
TOO_BIG = 1400
FITS = 1000


_run = harness._run


@pytest.fixture
def narrowed(fabric):
    """A guest behind its gateway, with a narrower hop past the gateway.

    The allow-list permits ICMP and nothing else, so the error coming back
    is admissible only as traffic related to what the guest sent -- the same
    position a real guest is in.
    """
    guest = fabric.add_guest("mt", vlan=41, ip="%s/24" % GUEST_IP)
    fabric.apply_egress(guest, VNI, CIDR, GW)
    fabric.apply_security_group(guest, [{"proto": "icmp"}])

    ns = hostns.vni_ns(VNI)
    # Both ends of the transfer veth: the sending end decides whether the
    # router complains, the far end whether the reply could come back.
    _run(
        [
            "ip",
            "netns",
            "exec",
            ns,
            "ip",
            "link",
            "set",
            "upl%d-ns" % VNI,
            "mtu",
            str(NARROW_MTU),
        ]
    )
    _run(["ip", "link", "set", "upl%d" % VNI, "mtu", str(NARROW_MTU)])
    return guest


def test_a_packet_too_big_for_the_path_is_answered_with_the_size_that_fits(narrowed):
    """The guest sends more than the path holds and must hear about it."""
    out = narrowed.exec(
        "ping", "-M", "do", "-s", str(TOO_BIG), "-c", "2", "-W", "2", FAR, check=False
    )

    assert "Frag needed" in out or "message too long" in out.lower(), (
        "the guest sent a packet too big for the path and heard nothing back "
        "(%r). Every large transfer it attempts will hang, and no log on "
        "either side will say why." % out.strip()
    )
    # iputils prints `mtu=1300` or `mtu = 1300`, depending on its version.
    assert "mtu=%d" % NARROW_MTU in out.replace(" ", ""), (
        "the guest was told its packet was too big but not what would fit, so "
        "it has nothing to retry with: %s" % out
    )


def test_the_guest_learns_the_size_and_keeps_it(narrowed):
    """Being told once has to change something, or it was only a message.

    What PMTUD is *for* is the route the guest caches afterwards. If the
    error arrives but leaves no trace, every subsequent large packet repeats
    the same round of loss, which is indistinguishable from working for one
    packet and broken for a transfer.
    """
    narrowed.exec(
        "ping", "-M", "do", "-s", str(TOO_BIG), "-c", "2", "-W", "2", FAR, check=False
    )

    route = narrowed.exec("ip", "route", "get", FAR)

    assert "mtu %d" % NARROW_MTU in route, (
        "the guest was told the path MTU and did not record it: %s" % route.strip()
    )


def test_a_packet_that_fits_is_forwarded_and_draws_no_complaint(narrowed):
    """The control: the narrowing must stop what is too big and nothing else.

    A gateway that complained about everything, or forwarded nothing, would
    satisfy the case above just as well. So a smaller packet has to draw no
    error *and* be seen leaving -- conntrack in the namespace is the witness
    that it was really forwarded and masqueraded, since nothing at the far
    end will answer to say so.
    """
    out = narrowed.exec(
        "ping", "-M", "do", "-s", str(FITS), "-c", "1", "-W", "1", FAR, check=False
    )

    assert "Frag needed" not in out, (
        "the gateway complained about a packet that fits the path: %s" % out
    )

    _, _, tr_ns = hostns.egress_transfer(VNI)
    conntrack = subprocess.run(
        [
            "ip",
            "netns",
            "exec",
            hostns.vni_ns(VNI),
            "conntrack",
            "-L",
            "-p",
            "icmp",
            "--src",
            GUEST_IP,
        ],
        capture_output=True,
        text=True,
    ).stdout
    assert tr_ns in conntrack, (
        "a packet that fits the path was never forwarded, so the case above "
        "proves only that this path drops everything"
    )
